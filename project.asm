FILL_ZEROES:
    JCXZ DONE
PAD_LOOP:
    MOV BYTE PTR [SI], '0'
    INC SI
    LOOP PAD_LOOP
DONE:
    RET
INP4DIGITS ENDP

CONV PROC
    XOR AX, AX                     
    MOV CX, 4                      
	LEA SI, SOLD                   
	MOV BX, 10                      

CONV_LOOP:
    MUL BX                         
    MOV DL, [SI]                    ; Read ASCII byte
    SUB DL, '0'                     ; Strip ASCII offset
    XOR DH, DH                      ; Clear DH
    ADD AX, DX                      ; AX = (AX * 10) + Digit
    INC SI                          ; Next character
    LOOP CONV_LOOP

    RET                             ; Converted value is returned in AX
CONV ENDP

END MAIN
