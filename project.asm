INP_LOOP:
    MOV AH, 01H                     
    INT 21H  

	CMP AL, '0'
    JB  NOMPTY               
    CMP AL, '9'
    JA  NOMPTY                  
    CMP AL, 0DH
    JE  FILL_ZEROES           
    
    MOV [SI], AL                    
    INC SI                          
    LOOP INP_LOOP
    RET
	
NOMPTY:
